    def test_cli_scan_red_links(self):
        cli = WikiTranslatorCLI(
            output_dir=str(self.tmp_dir),
            enable_map_links=False,
            enable_cache=False,
        )
        wikitext = (
            "Disutradarai oleh {{ill|Kevin Macdonald (sutradara)|en|Kevin Macdonald (director)}} "
            "dan diproduseri oleh {{ill|David Kosse|en|David Kosse}} bersama "
            "{{ill|Alfred Enoch|en|Alfred Enoch}}."
        )
        red_links = cli.scan_red_links(wikitext)
        self.assertEqual(len(red_links), 3)
        self.assertEqual(red_links[0]["id_title"], "Kevin Macdonald (sutradara)")
        self.assertEqual(red_links[0]["en_title"], "Kevin Macdonald (director)")
        self.assertEqual(red_links[1]["id_title"], "David Kosse")
        self.assertEqual(red_links[1]["en_title"], "David Kosse")
        self.assertEqual(red_links[2]["id_title"], "Alfred Enoch")
        self.assertEqual(red_links[2]["en_title"], "Alfred Enoch")

    def test_cli_interactive_red_link_selection(self):
        mock_stub_gen = MagicMock(spec=StubGenerator)
        mock_stub_gen.generate_stub.return_value = {
            "id_title": "David Kosse",
            "en_title": "David Kosse",
            "wikitext": "Stub",
        }
        mock_stub_gen.save_stub.return_value = self.tmp_dir / "stubs" / "David_Kosse.wikitext"

        cli = WikiTranslatorCLI(
            output_dir=str(self.tmp_dir),
            create_stubs=False,
            stub_generator=mock_stub_gen,
            enable_map_links=False,
            enable_cache=False,
        )
        wikitext = (
            "{{ill|Kevin Macdonald|en|Kevin Macdonald (director)}} dan "
            "{{ill|David Kosse|en|David Kosse}}."
        )
        # Select only #2 (David Kosse)
        with patch("builtins.input", return_value="2"):
            created = cli._process_red_links_and_stubs(wikitext, is_interactive=True)

        self.assertEqual(created, 1)
        mock_stub_gen.generate_stub.assert_called_once_with(
            en_title="David Kosse",
            id_title="David Kosse",
            topic=None,
        )

