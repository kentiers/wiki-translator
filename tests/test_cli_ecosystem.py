    def test_cli_audit_navboxes_and_docs_generates_files(self):
        """Tests that --audit-navboxes scans missing navboxes and creates templates & docs in output/templates/."""
        mock_navbox_gen = MagicMock(spec=NavboxGenerator)
        mock_navbox_gen.generate_navbox.return_value = {
            "template_name": "Christopher Nolan",
            "id_title": "Templat:Christopher Nolan",
            "wikitext": "{{Kotak navigasi|nama=Christopher Nolan}}",
            "already_exists": False,
        }
        mock_navbox_gen.save_navbox.side_effect = lambda info, d: (Path(d) / "templates" / f"{info['template_name']}.wikitext")

        mock_doc_auditor = MagicMock(spec=TemplateDocAuditor)
        mock_doc_auditor.audit_and_generate.return_value = {
            "template_name": "Christopher Nolan",
            "wikitext": "<!-- Dokumentasi -->",
        }
        mock_doc_auditor.save_doc.side_effect = lambda info, d: (Path(d) / "templates" / f"{info['template_name']}_doc.wikitext")

        cli = WikiTranslatorCLI(
            output_dir=str(self.tmp_dir),
            audit_navboxes=True,
            navbox_generator=mock_navbox_gen,
            template_doc_auditor=mock_doc_auditor,
            enable_map_links=False,
            enable_cache=False,
            enable_compression=False,
            enable_delta_skip=False,
            enable_auto_glossary=False,
        )

        section = WikiSection(
            index=1,
            title="Navigasi",
            level=2,
            header_raw="== Referensi ==\n{{Daftar rujukan}}",
            content="{{Christopher Nolan}}",
            word_count=2,
            char_count=25,
            translated_content="== Referensi ==\n{{Daftar rujukan}}\n\n{{Christopher Nolan}}",
        )

        cli._save_output("film_nolan", "Film Nolan", [section])
        mock_navbox_gen.generate_navbox.assert_called_once_with("Christopher Nolan", check_existence=True)
        mock_navbox_gen.save_navbox.assert_called_once()
        mock_doc_auditor.audit_and_generate.assert_called_once()
        mock_doc_auditor.save_doc.assert_called_once()

