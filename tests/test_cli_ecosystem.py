    def test_save_output_with_metric_first_and_enrich_archives(self):
        """Tests that _save_output runs metric_first, enrich_archives, and records shared memory."""
        from wiki_translator.wiki_client import WikiSection
        cli = WikiTranslatorCLI(
            output_dir=str(self.tmp_dir),
            enable_map_links=False,
            enable_typography_sanitizer=False,
            enable_slop_linter=False,
            enable_syntax_balancer=False,
            enable_template_mapper=False,
            metric_first=True,
            enrich_archives=True,
            check_media=True,
        )
        cli.custom_glossary = {"director": "sutradara"}

        section = WikiSection(
            index=0,
            title="Lead",
            level=1,
            header_raw="",
            content="Jaraknya 100 miles (160 km). {{cite web|url=https://example.com}}",
            word_count=10,
            char_count=60,
            translated_content="Jaraknya 100 miles (160 km). {{cite web|url=https://example.com}}",
        )

        with patch("wiki_translator.cli.default_reference_checker.enrich_citations_with_archives") as mock_enrich:
            mock_enrich.side_effect = lambda wt: wt.replace("{{cite web|url=https://example.com}}", "{{cite web|url=https://example.com|archive-url=https://web.archive.org/web/1/https://example.com}}")
            with patch("wiki_translator.cli.default_media_manager.audit_article_media") as mock_audit:
                mock_audit.return_value = []
                with patch("wiki_translator.cli.default_shared_memory.remember_term") as mock_remember:
                    outputs = cli._save_output(slug="sample", title="Sample", sections=[section])
                    self.assertTrue(outputs.wikitext.exists())
                    content = outputs.wikitext.read_text(encoding="utf-8")
                    self.assertIn("160 km (100 mil)", content)
                    self.assertIn("archive-url", content)
                    mock_remember.assert_called_with("director", "sutradara", topic=None)
                    mock_audit.assert_called_once()


